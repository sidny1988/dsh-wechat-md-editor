/**
 * 构建脚本：把 src/*.js 拼成单文件 client.js。
 *
 * 宿主（DSH）用 window.__ModuleLoader__.load 装载客户端插件，运行时只注入
 * React 等少量模块，所以这里不产出 chunk、不引入打包器，保持「单文件、
 * 零依赖、可读」的形态，便于在 profile 里直接调试。
 */
import { readFile, writeFile } from 'node:fs/promises'

const here = new URL('./', import.meta.url)
const parts = ['engine.js', 'highlight.js', 'themes.js', 'templates.js', 'htmlmd.js', 'check.js', 'inline.js', 'rich.js', 'css.js', 'ui.js', 'workbench.js', 'panel.js']

const chunks = []
for (const part of parts) {
  const text = await readFile(new URL('src/' + part, here), 'utf8')
  chunks.push('/* ============================== ' + part + ' ============================== */\n' + text.trim() + '\n')
}

const head = `/**
 * dsh-md-workbench · 公众号MD编辑器 —— Client half (generated by build.mjs, do not edit)
 *
 * 公众号 Markdown 编辑工作台：左侧栏入口 + 整页面板。
 * 三栏：草稿/大纲 · 编辑器 · 公众号预览；主题样式与复制内联共用同一份 CSS。
 */
window.__ModuleLoader__.load({
  id: 'dsh-md-workbench',
  factory(require) {
    const React = require('react')
    const h = React.createElement
    const { useCallback, useEffect, useLayoutEffect, useMemo, useRef, useState } = React

`

const tail = `
  }
})
`

const output = head + chunks.join('\n') + tail
await writeFile(new URL('client.js', here), output, 'utf8')
console.log('client.js · ' + (Buffer.byteLength(output) / 1024).toFixed(1) + ' KB · ' + parts.length + ' parts')
